// Session State Management
function getCurrentUser() {
  try {
    const raw = localStorage.getItem('virasat_user');
    return raw ? JSON.parse(raw) : null;
  } catch (e) {
    return null;
  }
}

function setCurrentUser(user, token = null) {
  if (user) {
    localStorage.setItem('virasat_user', JSON.stringify(user));
    if (token) localStorage.setItem('virasat_token', token);
  } else {
    localStorage.removeItem('virasat_user');
    localStorage.removeItem('virasat_token');
  }
  updateAuthUI();
}

function showAuthFeedback(message, type = 'info') {
  if (!authFeedback) return;
  authFeedback.className = `auth-feedback is-visible ${type}`;
  authFeedback.textContent = message;
  
  if (type === 'success') {
    setTimeout(() => {
      authFeedback.className = 'auth-feedback';
      authFeedback.textContent = '';
    }, 4000);
  }
}

function switchAuthTab(tabName) {
  const tabs = [
    { name: 'signin', btn: tabBtnSignin, panel: panelSignin },
    { name: 'signup', btn: tabBtnSignup, panel: panelSignup },
    { name: 'join', btn: tabBtnJoin, panel: panelJoin },
    { name: 'profile', btn: null, panel: panelProfile }
  ];

  tabs.forEach(t => {
    if (t.btn) t.btn.classList.toggle('active', t.name === tabName);
    if (t.panel) t.panel.style.display = (t.name === tabName) ? 'flex' : 'none';
  });

  if (authFeedback) {
    authFeedback.className = 'auth-feedback';
    authFeedback.textContent = '';
  }
}

function updateAuthUI() {
  const user = getCurrentUser();
  
  if (user) {
    const displayName = user.full_name || (user.email ? user.email.split('@')[0] : 'Explorer');
    const initial = (displayName.charAt(0) || 'U').toUpperCase();
    
    if (headerAuthLabel) headerAuthLabel.textContent = displayName.length > 12 ? displayName.substring(0, 10) + '..' : displayName;
    if (headerAuthTrigger) {
      headerAuthTrigger.classList.add('logged-in');
      headerAuthTrigger.title = `Logged in as ${user.email}`;
    }
    
    if (profileUserName) profileUserName.textContent = displayName;
    if (profileUserEmail) profileUserEmail.textContent = user.email || '';
    if (profileAvatarInitial) profileAvatarInitial.textContent = initial;

    if (authTabsBar) authTabsBar.style.display = 'none';
    switchAuthTab('profile');
  } else {
    if (headerAuthLabel) headerAuthLabel.textContent = 'Sign In';
    if (headerAuthTrigger) {
      headerAuthTrigger.classList.remove('logged-in');
      headerAuthTrigger.title = 'Sign In / Register';
    }
    if (authTabsBar) authTabsBar.style.display = 'flex';
    switchAuthTab('signin');
  }
}

