async function fetchMonumentDataFromGemini(monumentName) {
  const info = document.getElementById('wireframe-info');
  if (info) {
    info.innerHTML = `<strong>[QUERYING GEMINI KNOWLEDGE BASE...]</strong><br>Fetching verified historical telemetry for ${monumentName}...`;
  }

  const prompt = `Provide precise, verified historical facts about the Indian monument "${monumentName}". Return ONLY a JSON object with these exact keys: "name", "dynasty", "location", "heightOrSpan", "material", and "verifiedFact". No markdown wrappers outside JSON.`;

  try {
    const response = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash:generateContent?key=${GEMINI_API_KEY}`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        contents: [{ parts: [{ text: prompt }] }]
      })
    });

    const data = await response.json();
    const rawText = data.candidates[0].content.parts[0].text;
    
    // Clean up markdown code blocks if Gemini returns them
    const cleanJson = rawText.replace(/```json/g, '').replace(/```/g, '').trim();
    const result = JSON.parse(cleanJson);

    if (info) {
      info.innerHTML = `
        <strong style="color: #ffcc00;">[VERIFIED BY GEMINI AI: ${result.name.toUpperCase()}]</strong><br>
        📍 Location: ${result.location} | Era: ${result.dynasty}<br>
        🏛️ Specs: ${result.heightOrSpan} | Material: ${result.material}<br>
        <span style="color: #4bb543;">✓ Fact: ${result.verifiedFact}</span>
      `;
    }
  } catch (error) {
    console.error("Gemini API Error:", error);
    if (info) {
      info.innerHTML = `<span style="color: #ff4d4d;">⚠️ Failed to fetch live data. Please verify your Gemini API key.</span>`;
    }
  }
}

