async function analyzeArtifactWithGemini(base64Data, mimeType) {
  // UI Loading State
  ch3Telemetry.style.opacity = '1';
  document.getElementById('ch3-era-output').textContent = "Scanning Morphology...";
  document.getElementById('ch3-script-type').textContent = "Identifying script family...";
  document.getElementById('ch3-glyph-output').textContent = "Extracting...";
  document.getElementById('ch3-translation-output').textContent = "Cross-referencing ancient lexicons...";
  document.getElementById('ch3-context-output').textContent = "Retrieving archaeological context...";

  // The prompt that differentiates this from Google Lens
  const prompt = `Act as an expert epigraphist and archaeologist specializing in ancient Indian history. Analyze the uploaded image of the inscription or manuscript. 
  Do not just translate it. Analyze the stroke morphology to estimate its era and dynasty. 
  Return ONLY a JSON object with these exact keys:
  "estimatedEra" (e.g., "3rd Century BCE - Mauryan Empire"),
  "scriptFamily" (e.g., "Ashokan Brahmi" or "Grantha Script"),
  "extractedGlyphs" (The raw text in the original ancient script or closest Unicode equivalent),
  "modernTranslation" (The English translation),
  "archaeologicalContext" (2-3 sentences explaining the historical significance of this specific type of edict/text).
  No markdown wrappers.`;

  try {
    const response = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash:generateContent?key=${GEMINI_API_KEY}`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        contents: [{
          parts: [
            { text: prompt },
            { inline_data: { mime_type: mimeType, data: base64Data } }
          ]
        }]
      })
    });
    
    const data = await response.json();
    const result = JSON.parse(data.candidates[0].content.parts[0].text.replace(/```json/g, '').replace(/```/g, '').trim());

    // Update UI and stop laser
    ch3Laser.style.display = 'none';
    document.getElementById('ch3-era-output').textContent = result.estimatedEra.toUpperCase();
    document.getElementById('ch3-script-type').textContent = `SCRIPT MATCH: ${result.scriptFamily.toUpperCase()}`;
    document.getElementById('ch3-glyph-output').textContent = result.extractedGlyphs;
    document.getElementById('ch3-translation-output').textContent = `"${result.modernTranslation}"`;
    document.getElementById('ch3-context-output').textContent = result.archaeologicalContext;

  } catch (error) {
    console.error("Epigraphic API Error:", error);
    ch3Laser.style.display = 'none';
    document.getElementById('ch3-era-output').textContent = "ANALYSIS FAILED";
    document.getElementById('ch3-context-output').textContent = "Ensure the image is clear and your Gemini Vision API key is active.";
  }
}

if (ch3FileInput) {
  ch3FileInput.addEventListener('change', (e) => {
    const file = e.target.files[0];
    if (!file) return;

    const reader = new FileReader();
    reader.onload = function(uploadEvent) {
      const fullBase64 = uploadEvent.target.result;
      const mimeType = file.type;
      const base64Data = fullBase64.split(',')[1];

      // Update Image Preview & Start Laser
      document.getElementById('ch3-upload-placeholder').style.display = 'none';
      const previewImg = document.getElementById('ch3-preview-img');
      previewImg.src = fullBase64;
      previewImg.style.display = 'block';
      ch3Laser.style.display = 'block';

      // Send to Gemini
      analyzeArtifactWithGemini(base64Data, mimeType);
    };
    reader.readAsDataURL(file);
  });
}
